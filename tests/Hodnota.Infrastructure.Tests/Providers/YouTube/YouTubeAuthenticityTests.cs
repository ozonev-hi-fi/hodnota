using AwesomeAssertions;

using Google.Apis.YouTube.v3.Data;

using Hodnota.Infrastructure.Providers.YouTube;

namespace Hodnota.Infrastructure.Tests.Providers.YouTube;

public class YouTubeAuthenticityTests
{
    [Theory]
    [InlineData("Metallica - Topic", true)]
    [InlineData("Nostromo - Topic", true)]
    [InlineData("Metallica", false)]
    [InlineData(null, false)]
    public void IsTopicChannelTitle_MatchesOnlyTheTopicSuffix(string? channelTitle, bool expected) =>
        YouTubeAuthenticity.IsTopicChannelTitle(channelTitle).Should().Be(expected);

    [Theory]
    [InlineData("OLAK5uy_kuX1PX8vApNMXS8Unv4yK7K7fpipFjEbc", true)]
    [InlineData("PLUHFk0JDea8OCs0FhiMyei4Lm-5j-S_px", false)]
    [InlineData(null, false)]
    public void IsOlakPlaylistId_MatchesOnlyTheOlakPrefix(string? playlistId, bool expected) =>
        YouTubeAuthenticity.IsOlakPlaylistId(playlistId).Should().Be(expected);

    [Theory]
    [InlineData("Provided to YouTube by Blackened Recordings", true)]
    [InlineData("Official music video", false)]
    [InlineData(null, false)]
    public void IsAutoGeneratedDescription_MatchesOnlyTheStandardPrefix(string? description, bool expected) =>
        YouTubeAuthenticity.IsAutoGeneratedDescription(description).Should().Be(expected);

    private static SearchResult VideoResult(string channelTitle) => new()
    {
        Id = new ResourceId { VideoId = "v1" },
        Snippet = new SearchResultSnippet { Title = "Nothing Else Matters", ChannelTitle = channelTitle },
    };

    private static SearchResult PlaylistResult(string playlistId, string channelTitle) => new()
    {
        Id = new ResourceId { PlaylistId = playlistId },
        Snippet = new SearchResultSnippet { Title = "Load", ChannelTitle = channelTitle },
    };

    [Fact]
    public void HasIntrinsicAuthenticity_TopicVideo_IsTrue() =>
        YouTubeAuthenticity.HasIntrinsicAuthenticity(VideoResult("Metallica - Topic")).Should().BeTrue();

    [Fact]
    public void HasIntrinsicAuthenticity_PirateUploadVideo_IsFalse() =>
        // The real somuchdeath18 pirate upload of Ecce Lex (docs/youtube-music-search.md section 1).
        YouTubeAuthenticity.HasIntrinsicAuthenticity(VideoResult("somuchdeath18")).Should().BeFalse();

    [Fact]
    public void HasIntrinsicAuthenticity_OlakPlaylistOwnedByYouTube_IsTrue() =>
        YouTubeAuthenticity.HasIntrinsicAuthenticity(PlaylistResult("OLAK5uy_nf8K8yHuLThX0qvPGCIM2eBKndPale4vU", "YouTube")).Should().BeTrue();

    [Fact]
    public void HasIntrinsicAuthenticity_OlakShapedIdOwnedBySomeoneElse_IsFalse() =>
        YouTubeAuthenticity.HasIntrinsicAuthenticity(PlaylistResult("OLAK5uy_fake", "A Random User")).Should().BeFalse();

    [Fact]
    public void HasIntrinsicAuthenticity_UserPlaylistNotOlakShaped_IsFalse() =>
        // The real "Nostromo Discography" fan playlist (docs/youtube-music-search.md section 1).
        YouTubeAuthenticity.HasIntrinsicAuthenticity(PlaylistResult("PLE8F8DBAADF4DFD20", "A Random User")).Should().BeFalse();
}
