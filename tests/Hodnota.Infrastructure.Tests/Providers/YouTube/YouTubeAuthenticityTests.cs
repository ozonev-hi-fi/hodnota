using AwesomeAssertions;

using Google.Apis.YouTube.v3.Data;

using Hodnota.Infrastructure.Providers.YouTube;

namespace Hodnota.Infrastructure.Tests.Providers.YouTube;

public class YouTubeAuthenticityTests
{
    [Theory]
    [InlineData("Metallica - Topic", true)]
    [InlineData("Nostromo - Topic", true)]
    [InlineData("Metallica", false)]
    [InlineData(null, false)]
    public void IsTopicChannelTitle_MatchesOnlyTheTopicSuffix(string? channelTitle, bool expected) =>
        YouTubeAuthenticity.IsTopicChannelTitle(channelTitle).Should().Be(expected);

    [Theory]
    [InlineData("Provided to YouTube by Blackened Recordings", true)]
    [InlineData("Official music video", false)]
    [InlineData(null, false)]
    public void IsAutoGeneratedDescription_MatchesOnlyTheStandardPrefix(string? description, bool expected) =>
        YouTubeAuthenticity.IsAutoGeneratedDescription(description).Should().Be(expected);

    private static SearchResult VideoResult(string channelTitle, string? description = "Provided to YouTube by Blackened Recordings") => new()
    {
        Id = new ResourceId { VideoId = "v1" },
        Snippet = new SearchResultSnippet { Title = "Nothing Else Matters", ChannelTitle = channelTitle, Description = description },
    };

    [Fact]
    public void HasIntrinsicAuthenticity_TopicVideoWithAutoGeneratedDescription_IsTrue() =>
        YouTubeAuthenticity.HasIntrinsicAuthenticity(VideoResult("Metallica - Topic")).Should().BeTrue();

    [Fact]
    public void HasIntrinsicAuthenticity_TopicVideoWithoutAutoGeneratedDescription_IsFalse() =>
        YouTubeAuthenticity.HasIntrinsicAuthenticity(VideoResult("Metallica - Topic", "my favourite song")).Should().BeFalse();

    [Fact]
    public void HasIntrinsicAuthenticity_PirateUploadVideo_IsFalse() =>
        // The real somuchdeath18 pirate upload of Ecce Lex (docs/youtube-music-search.md section 1).
        YouTubeAuthenticity.HasIntrinsicAuthenticity(VideoResult("somuchdeath18")).Should().BeFalse();

    [Fact]
    public void HasIntrinsicAuthenticity_Playlist_IsFalse() =>
        YouTubeAuthenticity.HasIntrinsicAuthenticity(new SearchResult
        {
            Id = new ResourceId { PlaylistId = "OLAK5uy_nf8K8yHuLThX0qvPGCIM2eBKndPale4vU" },
            Snippet = new SearchResultSnippet { Title = "Album - Load", ChannelTitle = "YouTube" },
        }).Should().BeFalse();
}
