using AwesomeAssertions;

using Google.Apis.YouTube.v3.Data;

using Hodnota.Application.Catalog;
using Hodnota.Infrastructure.Catalog;
using Hodnota.Infrastructure.Providers.YouTube;

using Microsoft.Extensions.Caching.Memory;

using NSubstitute;

namespace Hodnota.Infrastructure.Tests.Providers.YouTube;

// SearchAsync is the search-page wiring (ADR 0018 Phase 6): every row now needs an intrinsic
// authenticity signal (YouTubeAuthenticity), replacing the old weak word-match filter.
public class YouTubeStreamingProviderSearchTests
{
    private const string AutoGeneratedDescription = "Provided to YouTube by The Orchard Enterprises";

    private static IYouTubeApiClient NewApiClient() => Substitute.For<IYouTubeApiClient>();

    private static YouTubeChannelResolver NewChannelResolver(IYouTubeApiClient apiClient) =>
        new(apiClient, new MemoryCache(new MemoryCacheOptions()));

    private static SearchResult VideoResult(string videoId, string title, string channelTitle, string? description = AutoGeneratedDescription) => new()
    {
        Id = new ResourceId { VideoId = videoId },
        Snippet = new SearchResultSnippet { Title = title, ChannelTitle = channelTitle, Description = description },
    };

    private static void SetUpConfirmedChannel(IYouTubeApiClient apiClient, string artistName, string channelId, string sampledUploadTitle)
    {
        var uploadsPlaylistId = "UU" + channelId;
        apiClient.SearchChannelsAsync($"{artistName} - Topic", Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns([new SearchResult { Id = new ResourceId { ChannelId = channelId }, Snippet = new SearchResultSnippet { ChannelTitle = $"{artistName} - Topic" } }]);
        apiClient.GetUploadsPlaylistIdAsync(channelId, Arg.Any<CancellationToken>()).Returns(uploadsPlaylistId);
        apiClient.GetPlaylistItemsAsync(uploadsPlaylistId, Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns([new PlaylistItem { Snippet = new PlaylistItemSnippet { Title = sampledUploadTitle } }]);
    }

    [Fact]
    public async Task SearchAsync_Track_RejectsThePirateUploadAndKeepsTheTopicVideo()
    {
        var apiClient = NewApiClient();
        // The real 2026-10-01 search results for "nostromo ecce lex" (docs/youtube-music-search.md
        // section 1): a pirate full-album upload, an auto-generated "Mix", and the genuine Topic track.
        apiClient.SearchVideosAsync("nostromo ecce lex", null, null, Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns(
            [
                VideoResult("pirate1", "Nostromo - Ecce Lex (Full Album)", "somuchdeath18", description: "full album, enjoy"),
                VideoResult("mix1", "Mix - Nostromo", "YouTube Music", description: null),
                VideoResult("topic1", "Ecce Lex", "Nostromo - Topic"),
            ]);
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.SearchAsync("nostromo ecce lex", StreamingResultType.Track, CancellationToken.None);

        results.Should().ContainSingle().Which.Links.Should().Contain(l => l.ExternalId == "topic1");
    }

    [Fact]
    public async Task SearchAsync_Track_RejectsATopicNamedChannelWithoutTheAutoGeneratedDescription()
    {
        var apiClient = NewApiClient();
        apiClient.SearchVideosAsync("nostromo ecce lex", null, null, Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns([VideoResult("fake1", "Ecce Lex", "Nostromo - Topic", description: "uploaded by a fan")]);
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.SearchAsync("nostromo ecce lex", StreamingResultType.Track, CancellationToken.None);

        results.Should().BeEmpty();
    }

    [Fact]
    public async Task SearchAsync_Release_MakesNoApiCall()
    {
        var apiClient = NewApiClient();
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.SearchAsync("metallica load", StreamingResultType.Release, CancellationToken.None);

        results.Should().BeEmpty();
        apiClient.ReceivedCalls().Should().BeEmpty();
    }

    [Fact]
    public async Task FindByNameAsync_Track_GenuineTopicVideoMatchesTheArtistAndTitle()
    {
        var apiClient = NewApiClient();
        apiClient.SearchVideosAsync("Metallica Nothing Else Matters", null, null, Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns([VideoResult("v1", "Nothing Else Matters", "Metallica - Topic")]);
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.FindByNameAsync("Metallica", "Nothing Else Matters", StreamingResultType.Track, [], CancellationToken.None);

        results.Should().ContainSingle().Which.Links.Should().Contain(l => l.ExternalId == "v1");
    }

    [Fact]
    public async Task FindByNameAsync_Release_NoKnownTrackTitles_ReturnsNothingWithoutAnyApiCall()
    {
        var apiClient = NewApiClient();
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.FindByNameAsync("Nostromo", "Ecce Lex", StreamingResultType.Release, [], CancellationToken.None);

        results.Should().BeEmpty();
        apiClient.ReceivedCalls().Should().BeEmpty();
    }

    [Fact]
    public async Task FindByNameAsync_Release_FallsBackToAVerifiedTopicTrack()
    {
        var apiClient = NewApiClient();
        SetUpConfirmedChannel(apiClient, "Nostromo", "UCjbNuWiJ2t_hO5Yu8Eihi0w", "Rude Awakening (Stripped)");
        apiClient.SearchVideosAsync("Ecce Lex", "UCjbNuWiJ2t_hO5Yu8Eihi0w", 10, Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns([VideoResult("v-ecce-lex", "Ecce Lex", "Nostromo - Topic")]);
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.FindByNameAsync("Nostromo", "Ecce Lex", StreamingResultType.Release, ["Ecce Lex", "Rude Awakening"], CancellationToken.None);

        // The substitute is a Track result, labelled as a track (ADR 0018 D2), never the album.
        results.Should().ContainSingle().Which.Type.Should().Be(StreamingResultType.Track);
        results.Single().Links.Should().Contain(l => l.ExternalId == "v-ecce-lex" && l.PlatformCode == PlatformCodes.YouTubeMusic);
        await apiClient.DidNotReceive().SearchVideosAsync(Arg.Any<string>(), Arg.Is<string?>(channelId => channelId == null), Arg.Any<int?>(), Arg.Any<int>(), Arg.Any<CancellationToken>());
    }

    [Fact]
    public async Task FindByNameAsync_Release_SkipsAChannelResultFromAnotherAlbum()
    {
        // E9's real search inside Metallica's Topic channel for "Load" also returned ReLoad tracks.
        var apiClient = NewApiClient();
        SetUpConfirmedChannel(apiClient, "Metallica", "UCGexNm_Kw4rdQjLxmpb2EKw", "King Nothing");
        apiClient.SearchVideosAsync("Load", "UCGexNm_Kw4rdQjLxmpb2EKw", 10, Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns(
            [
                VideoResult("v-fuel", "Fuel", "Metallica - Topic"),
                VideoResult("v-king-nothing", "King Nothing", "Metallica - Topic"),
            ]);
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.FindByNameAsync("Metallica", "Load", StreamingResultType.Release, ["Ain't My Bitch", "2 X 4", "The House Jack Built", "Until It Sleeps", "King Nothing"], CancellationToken.None);

        results.Should().ContainSingle().Which.Links.Should().Contain(l => l.ExternalId == "v-king-nothing");
    }

    [Fact]
    public async Task FindByNameAsync_Release_NoChannelResultIsAKnownTrack_ReturnsNothing()
    {
        var apiClient = NewApiClient();
        SetUpConfirmedChannel(apiClient, "Metallica", "UCGexNm_Kw4rdQjLxmpb2EKw", "King Nothing");
        apiClient.SearchVideosAsync("Load", "UCGexNm_Kw4rdQjLxmpb2EKw", 10, Arg.Any<int>(), Arg.Any<CancellationToken>())
            .Returns([VideoResult("v-fuel", "Fuel", "Metallica - Topic")]);
        var provider = new YouTubeStreamingProvider(apiClient, NewChannelResolver(apiClient));

        var results = await provider.FindByNameAsync("Metallica", "Load", StreamingResultType.Release, ["King Nothing"], CancellationToken.None);

        results.Should().BeEmpty();
    }
}
