using Google.Apis.YouTube.v3.Data;

namespace Hodnota.Infrastructure.Providers.YouTube;

public static class YouTubeAuthenticity
{
    private const string TopicChannelSuffix = " - Topic";
    private const string AutoGeneratedDescriptionPrefix = "Provided to YouTube by";

    public static bool IsTopicChannelTitle(string? channelTitle) =>
        channelTitle is not null && channelTitle.EndsWith(TopicChannelSuffix, StringComparison.Ordinal);

    public static bool IsAutoGeneratedDescription(string? description) =>
        description is not null && description.StartsWith(AutoGeneratedDescriptionPrefix, StringComparison.Ordinal);

    public static bool HasIntrinsicAuthenticity(SearchResult item) =>
        item.Id.VideoId is not null
        && IsTopicChannelTitle(item.Snippet?.ChannelTitle)
        && IsAutoGeneratedDescription(item.Snippet?.Description);
}
